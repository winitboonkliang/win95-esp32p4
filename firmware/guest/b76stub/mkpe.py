#!/usr/bin/env python3
"""Own minimal PE32 writer for the B76 guest stub (no Microsoft code, no toolchain beyond GNU as/ld).
usage: mkpe.py <out.exe> <imports.inc out> <imports.rs out> [code.bin]
Pass 1 (no code.bin): writes imports.inc / imports.rs (IAT addresses fixed: .idata at RVA 0x2000).
Pass 2 (code.bin = raw i386 code linked at 0x401000): writes the .exe.
Layout: .text RVA 0x1000 (code, <= 4 KB), .idata RVA 0x2000, .bss RVA 0x3000 (SHARED_SIZE, uninitialised = host shared area)."""
import struct, sys

BASE, TEXT, IDATA, BSS = 0x400000, 0x1000, 0x2000, 0x3000
SHARED_SIZE = 0x400000
# ONE flat list: the index is the call number the host uses (imports.rs). Order matters; append only.
IMPORTS = [
    ('KERNEL32.dll', ['GetModuleHandleA', 'GetCommandLineA', 'ExitProcess', 'CreateFileA', 'ReadFile', 'WriteFile',
                      'CloseHandle', 'GlobalAlloc', 'GlobalLock', 'GlobalUnlock', 'GetFileSize', 'GlobalAddAtomA']),
    ('USER32.dll', ['RegisterClassA', 'CreateWindowExA', 'DefWindowProcA', 'GetMessageA', 'TranslateMessage',
                    'DispatchMessageA', 'ShowWindow', 'UpdateWindow', 'BeginPaint', 'EndPaint', 'CreateMenu',
                    'CreatePopupMenu', 'AppendMenuA', 'SetMenu', 'CheckMenuItem', 'EnableMenuItem', 'DrawMenuBar',
                    'SetWindowTextA', 'MessageBoxA', 'PostQuitMessage', 'DestroyWindow', 'InvalidateRect',
                    'OpenClipboard', 'CloseClipboard', 'EmptyClipboard', 'SetClipboardData', 'GetClipboardData',
                    'IsClipboardFormatAvailable', 'LoadCursorA', 'LoadIconA', 'GetClientRect', 'SetFocus',
                    'ClientToScreen', 'PostMessageA', 'SendMessageA', 'PackDDElParam']),
    ('GDI32.dll', ['SetDIBitsToDevice', 'GetStockObject']),
    ('COMDLG32.dll', ['GetOpenFileNameA', 'GetSaveFileNameA']),
    ('ADVAPI32.dll', ['RegSetValueA']),
]

def build_idata():
    """returns (bytes, {name: iat_va}, flat name list); everything inside one 4 KB page at RVA IDATA."""
    ndll = len(IMPORTS)
    desc_sz = 20 * (ndll + 1)
    nthunk = sum(len(f) + 1 for _, f in IMPORTS)
    ilt_off = desc_sz; iat_off = ilt_off + 4 * nthunk; names_off = iat_off + 4 * nthunk
    names = bytearray(); hint_rva = {}; dll_rva = {}
    for dll, funcs in IMPORTS:
        for f in funcs:
            if len(names) & 1: names += b'\0'
            hint_rva[f] = IDATA + names_off + len(names); names += struct.pack('<H', 0) + f.encode() + b'\0'
        dll_rva[dll] = IDATA + names_off + len(names); names += dll.encode() + b'\0'
    buf = bytearray(names_off + len(names))
    t = 0; iat = {}; flat = []
    for i, (dll, funcs) in enumerate(IMPORTS):
        struct.pack_into('<IIIII', buf, 20 * i, IDATA + ilt_off + 4 * t, 0, 0, dll_rva[dll], IDATA + iat_off + 4 * t)
        for f in funcs:
            struct.pack_into('<I', buf, ilt_off + 4 * t, hint_rva[f]); struct.pack_into('<I', buf, iat_off + 4 * t, hint_rva[f])
            iat[f] = BASE + IDATA + iat_off + 4 * t; flat.append(f); t += 1
        t += 1  # null terminator
    buf[names_off:] = names
    assert len(buf) <= 0x1000
    return bytes(buf), iat, flat, (IDATA + iat_off, 4 * nthunk)

def pad(b, n): return b + b'\0' * (-len(b) % n)

def main():
    out, inc, rs = sys.argv[1:4]
    idata, iat, flat, iatdir = build_idata()
    with open(inc, 'w') as f:
        f.write('# generated by mkpe.py\n.set SHARED, 0x%x\n.set SHARED_SIZE, 0x%x\n' % (BASE + BSS, SHARED_SIZE))
        for n in flat: f.write('.set imp_%s, 0x%x\n' % (n, iat[n]))
        f.write('.macro FNTAB\n' + ''.join('.long 0x%x\n' % iat[n] for n in flat) + '.endm\n')
    with open(rs, 'w') as f:
        f.write('// generated by stub/mkpe.py: call numbers of the B76 stub (index into its import table)\n')
        f.write('pub const SHARED: u32 = 0x%x;\npub const SHARED_SIZE: u32 = 0x%x;\n' % (BASE + BSS, SHARED_SIZE))
        for i, n in enumerate(flat): f.write('pub const %s: u32 = %d;\n' % (n.upper(), i))
    if len(sys.argv) < 5: return
    code = open(sys.argv[4], 'rb').read(); assert len(code) <= 0x1000, len(code)
    secs = [(b'.text', TEXT, 0x1000, pad(code, 0x200), 0xE0000020),        # code + stub state (depth, msg): exec, read, write
            (b'.idata', IDATA, 0x1000, pad(idata, 0x200), 0xC0000040),     # init data, read, write
            (b'.bss', BSS, SHARED_SIZE, b'', 0xC0000080)]                  # uninit data, read, write
    hdr = bytearray(0x200)
    # MZ header every 1995 loader accepts: e_lfarlc = 0x40 marks a new-format exe; 4-byte DOS stub (int 21h AH=4Ch) at 0x40
    struct.pack_into('<2sHHHHHHHHHHHHH', hdr, 0, b'MZ', 0x90, 1, 0, 4, 0, 0xffff, 0, 0xb8, 0, 0, 0, 0x40, 0)
    hdr[0x40:0x44] = bytes([0xb4, 0x4c, 0xcd, 0x21]); struct.pack_into('<I', hdr, 0x3c, 0x80)
    hdr[0x80:0x84] = b'PE\0\0'
    struct.pack_into('<HHIIIHH', hdr, 0x84, 0x14c, len(secs), 0, 0, 0, 224, 0x010F)
    o = 0x98
    size_image = BSS + SHARED_SIZE
    struct.pack_into('<HBBIIIIIIIIIHHHHHHIIIIHHIIIIII', hdr, o,
                     0x10b, 2, 50, 0x1000, 0x1000, SHARED_SIZE, TEXT, TEXT, IDATA,
                     BASE, 0x1000, 0x200, 4, 0, 0, 0, 4, 0, 0, size_image, 0x200, 0, 2, 0,
                     0x100000, 0x1000, 0x100000, 0x1000, 0, 16)
    dd = o + 96
    struct.pack_into('<II', hdr, dd + 8 * 1, IDATA, len(idata))      # import directory
    struct.pack_into('<II', hdr, dd + 8 * 12, *iatdir)               # IAT
    sh = o + 224; fptr = 0x200
    for i, (name, rva, vsz, raw, ch) in enumerate(secs):
        struct.pack_into('<8sIIIIIIHHI', hdr, sh + 40 * i, name, vsz, rva, len(raw), fptr if raw else 0, 0, 0, 0, 0, ch)
        fptr += len(raw)
    img = bytes(hdr) + b''.join(s[3] for s in secs)
    open(out, 'wb').write(img)
    print('wrote', out, len(img), 'bytes; code', len(code))

if __name__ == '__main__': main()
