"""B82: hooks/b82_datainit.c = calls of every b82i_<file>() that the component compiles (run in components/doomp4 after b82_data2psram.py)"""
import os, re, sys
DG = sys.argv[1] if len(sys.argv) > 1 else 'dg'; OUT = sys.argv[2] if len(sys.argv) > 2 else 'hooks/b82_datainit.c'   # run in components/doomp4
c = open('CMakeLists.txt').read()
srcs = re.search(r'set\(DG_SRCS(.*?)\)', c, re.S).group(1).split() + re.search(r'set\(OPL_SRCS(.*?)\)', c, re.S).group(1).split()   # B84: + OPL
H = ('i_system.c', 'm_config.c', 'info.c', 'sounds.c')
bases = [re.sub(r'\W', '_', os.path.basename(s)[:-2]) for s in srcs if s[0] != '#' and 'void b82i_' in open(s if s.startswith('opl/') else ('hooks/' if s in H else DG + '/') + s, encoding='latin-1').read()]
g = '/* B82: generated by tools/b82_gen_init.py - initial values of the engine globals, flash -> PSRAM, once before D_DoomMain */\n'
g += ''.join('void b82i_%s(void);\n' % b for b in bases) + 'void b82_data_init(void)\n{\n' + ''.join('    b82i_%s();\n' % b for b in bases) + '}\n'
open(OUT, 'w').write(g); print(len(bases), 'files')
