/* B85: PC self-test of esp/main/b85hid.c. gcc -I../../esp/main test_hid.c ../../esp/main/b85hid.c && ./a.out */
#include <stdio.h>
#include <assert.h>
#include "b85hid.h"

/* Logitech F310 D mode (Dual Action layout): X Y Z Rz 8-bit, hat 4 bit, 12 buttons, 16 vendor bits */
static const uint8_t f310d[] = {
	0x05,0x01,0x09,0x04,0xA1,0x01,0xA1,0x02,0x75,0x08,0x95,0x04,0x15,0x00,0x26,0xFF,0x00,0x35,0x00,0x46,0xFF,0x00,
	0x09,0x30,0x09,0x31,0x09,0x32,0x09,0x35,0x81,0x02,0x75,0x04,0x95,0x01,0x25,0x07,0x46,0x3B,0x01,0x65,0x14,0x09,0x39,
	0x81,0x42,0x65,0x00,0x75,0x01,0x95,0x0C,0x25,0x01,0x45,0x01,0x05,0x09,0x19,0x01,0x29,0x0C,0x81,0x02,0x06,0x00,0xFF,
	0x75,0x01,0x95,0x10,0x25,0x01,0x45,0x01,0x09,0x01,0x81,0x02,0xC0,0xA1,0x02,0x75,0x08,0x95,0x07,0x46,0xFF,0x00,0x26,
	0xFF,0x00,0x09,0x02,0x91,0x02,0xC0,0xC0 };
/* report ID 1, DualShock-like: X Y Z Rz, hat (null 8), 14 buttons, 6 bits pad, Rx Ry triggers; report ID 2 = output-only junk */
static const uint8_t ds[] = {
	0x05,0x01,0x09,0x05,0xA1,0x01,0x85,0x01,0x09,0x30,0x09,0x31,0x09,0x32,0x09,0x35,0x15,0x00,0x26,0xFF,0x00,0x75,0x08,0x95,0x04,0x81,0x02,
	0x09,0x39,0x15,0x00,0x25,0x07,0x75,0x04,0x95,0x01,0x81,0x42,0x05,0x09,0x19,0x01,0x29,0x0E,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x0E,0x81,0x02,
	0x75,0x06,0x95,0x01,0x81,0x01,0x05,0x01,0x09,0x33,0x09,0x34,0x15,0x00,0x26,0xFF,0x00,0x75,0x08,0x95,0x02,0x81,0x02,
	0x85,0x02,0x09,0x01,0x75,0x08,0x95,0x04,0x91,0x02,0xC0 };
/* boot keyboard: not a pad */
static const uint8_t kbd[] = { 0x05,0x01,0x09,0x06,0xA1,0x01,0x05,0x07,0x19,0xE0,0x29,0xE7,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x08,0x81,0x02,
	0x95,0x01,0x75,0x08,0x81,0x01,0x95,0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07,0x19,0x00,0x29,0x65,0x81,0x00,0xC0 };

static b85hid_t h;
int main(void)
{
	b85pad_t p;
	assert(b85hid_parse(f310d, sizeof f310d, &h) && !h.has_id && h.nbtn[0] == 12);
	/* old port's layout: d[0..3] LX LY RX RY, d[4] low nibble hat, high nibble X A B Y, d[5] LB RB LT RT Back Start L3 R3 */
	uint8_t r1[8] = { 255, 128, 0, 128, 0x08 | 0x20, 0x02 | 0x80, 0, 0 };   /* LX right, RX left, hat centered (8), A, RB, R3 */
	assert(b85hid_decode(&h, r1, 8, &p));
	printf("f310d: lx %d ly %d rx %d ry %d btn %05x\n", p.lx, p.ly, p.rx, p.ry, (unsigned)p.btn);
	assert(p.lx == 127 && p.ly == 0 && p.rx == -127 && p.ry == 0);
	assert(p.btn == (1u << B85B_A | 1u << B85B_RB | 1u << B85B_RS));
	uint8_t r2[8] = { 128, 128, 128, 128, 0x02 | 0x10, 0x40 | 0x08, 0, 0 };   /* hat E, X, RT, ... 0x40 = button 15? no: d[5] bit6 = L3 */
	assert(b85hid_decode(&h, r2, 8, &p));
	assert(p.btn == (1u << B85B_RIGHT | 1u << B85B_X | 1u << B85B_RT | 1u << B85B_LS));
	uint8_t r3[8] = { 128, 0, 128, 128, 0x07, 0, 0, 0 };   /* hat NW, LY up */
	assert(b85hid_decode(&h, r3, 8, &p) && p.ly == -127 && p.btn == (1u << B85B_UP | 1u << B85B_LEFT));

	assert(b85hid_parse(ds, sizeof ds, &h) && h.has_id && h.nbtn[1] == 14);
	uint8_t d1[9] = { 1, 128, 128, 255, 0, 0x08 | 0x40, 0x01, 0x00, 0 };   /* RX full right, RY up, hat null, button 3 (B), button 9 (Back) */
	uint8_t d1b[10] = { 1, 128, 128, 255, 0, 0x08 | 0x40, 0x10, 0x00, 255, 0 };   /* + Rx (L2 analog) full */
	assert(b85hid_decode(&h, d1b, 10, &p));
	printf("ds: rx %d ry %d lt %d rt %d btn %05x\n", p.rx, p.ry, p.lt, p.rt, (unsigned)p.btn);
	assert(p.rx == 127 && p.ry == -127 && p.lt == 255 && p.rt == 0 && p.btn == (1u << B85B_B | 1u << B85B_BACK | 1u << B85B_LT));   /* analog L2 past 30 % = LT button too */
	(void)d1;
	uint8_t d2[5] = { 2, 1, 2, 3, 4 };
	assert(!b85hid_decode(&h, d2, 5, &p));   /* report 2 has no inputs */
	assert(!b85hid_parse(kbd, sizeof kbd, &h));

	uint8_t x[20] = { 0x00, 0x14, 0x01 | 0x10, 0x10 | 0x80, 0, 255, 0x00, 0x80, 0xFF, 0x7F, 0, 0, 0, 0 };   /* up, start, A, Y, RT; LX -32768, LY +32767 (up) */
	assert(b85x360_decode(x, 20, &p));
	printf("x360: lx %d ly %d rt %d btn %05x\n", p.lx, p.ly, p.rt, (unsigned)p.btn);
	assert(p.lx == -127 && p.ly == -127 && p.btn == (1u << B85B_UP | 1u << B85B_START | 1u << B85B_A | 1u << B85B_Y | 1u << B85B_RT));
	puts("b85hid: all PASS");
	return 0;
}
