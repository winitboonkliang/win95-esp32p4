#include <stdio.h>

#include "m_argv.h"

#include "doomgeneric.h"

static pixel_t* const DG_ScreenBuffer__b82i = NULL;  /* B82: initial value in flash */
pixel_t* DG_ScreenBuffer;  /* B82: live copy, .bss -> PSRAM */

void M_FindResponseFile(void);
void D_DoomMain (void);


void doomgeneric_Create(int argc, char **argv)
{
	// save arguments
    myargc = argc;
    myargv = argv;

	M_FindResponseFile();

	// ESP32-P4 port: the platform layer may pre-allocate DG_ScreenBuffer in
	// internal SRAM (CMAP256 → 1 byte/pixel) before doomgeneric_Create runs.
	if (!DG_ScreenBuffer)
		DG_ScreenBuffer = malloc(DOOMGENERIC_RESX * DOOMGENERIC_RESY * sizeof(pixel_t));

	DG_Init();

	D_DoomMain ();
}


/* B82_DATA2PSRAM: generated by lab:LEAD/B82/tools/b82_data2psram.py */
#include <string.h>
void b82i_doomgeneric(void)
{
    memcpy((void *)&DG_ScreenBuffer, (const void *)&DG_ScreenBuffer__b82i, sizeof DG_ScreenBuffer__b82i);
}
