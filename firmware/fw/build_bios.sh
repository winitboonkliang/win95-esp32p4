#!/bin/bash
# assemble bios.S -> bios.bin (64 KB) and generate ../rust/fwhost/src/syms.rs (guest entry offsets used by the host-built IVT). WSL/Linux binutils.
cd "$(dirname "$0")"
as --32 -o bios.o bios.S && ld -m elf_i386 -Ttext=0 -o bios.elf bios.o 2>/dev/null && objcopy -O binary bios.elf bios.bin
python3 -c "
d=bytearray(open('bios.bin','rb').read()); p=0x7DD0
assert d[p:p+4]==b'\$PnP' and d[p+5]==0x21; d[p+8]=(-sum(d[p:p+0x21]))&255   # PnP header checksum
d[-1]=(-sum(d[:-1]))&255; open('bios.bin','wb').write(d)"
{ echo "// generated by tools/build_bios.sh from fw/bios.S - do not edit"; 
  for s in dummy_iret irq_master_eoi irq_slave_eoi int08 int09 int10 font16 font8 oem int11 int12 int13 int14 int15 int16 int17 int18 int19 int1a int70 int74 int75 apm32_entry hd0_table diskette_table sysconf; do
    a=$(nm bios.elf | awk -v s=$s '$3==s{print $1}'); echo "pub const $(echo $s | tr a-z A-Z): u16 = 0x$a;"; done; } > ../rust/fwhost/src/syms.rs
ls -l bios.bin
